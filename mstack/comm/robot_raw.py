"""1 kHz 로봇 원시 상태의 전선 형식 -- 발행자(노드)와 구독자(로거)의 정본.

**왜 필요한가.** 에피소드 HDF5 는 20 Hz 로 기록된다. 나이퀴스트가 10 Hz 라
손으로 느껴지는 진동(대개 20~100 Hz)은 원리적으로 그 데이터에 안 잡힌다.
2026-09-10 에 조작자가 "테이블에 손을 올리면 진동이 느껴진다" 고 보고했을 때,
있는 자료로는 없다고도 있다고도 말할 수 없었다 -- 안 보이는 것이지 없는 것이
아니었다. 제어 루프는 이미 1 kHz 로 이 값들을 읽고 있으므로, 흘려보내기만
하면 500 Hz 까지 관측할 수 있다.

**왜 PUB/SUB 인가.** 로그는 응답이 필요 없고 최신값만 필요하다 -- 카메라와
같은 성질이다. 로봇 노드의 REQ/REP 는 엄격한 락스텝이라 거기에 얹으면 진단이
제어 경로의 실패를 공유하게 된다. PUB 은 구독자가 없어도, 느려도, 죽어도
블로킹하지 않는다.

**왜 스레드가 아니라 프로세스인가.** 파이썬 GIL 전환 간격은 기본 5 ms 다.
쓰기를 같은 프로세스의 스레드로 두면 그 스레드가 순수 파이썬 구간을 도는
동안 제어 루프가 최대 5 ms 멈춘다 -- 틱 5개 분량이고, late tick 판정선은
1.5 ms 다. 실측으로도 파이썬 작업 스레드를 붙이면 1 kHz 루프의 **모든** 틱이
늦었다 (486/486). 구독자를 다른 프로세스에 두면 GIL 이 아예 분리된다.

루프가 내는 비용은 실측 0.75 µs/tick -- 1 ms 예산의 0.07% 다.

전선 형식은 float64 36개(288 B)로 단순하게 둔다. 저장할 때 로거가 시각만
float64 로 남기고 나머지를 float32 로 낮춘다.
"""

from __future__ import annotations

#: 원시 상태 PUB 포트. 6001 로봇 REQ/REP, 6021/6022 카메라 노드와 겹치지 않는다.
DEFAULT_RAW_PORT = 6031

RAW_TOPIC = b"fr3raw"

#: 1 이면 노드가 발행하지 않는다. 로봇 노드 쪽 계약 --
#: GELLO_NO_PHASE_BUS(워커 쪽)와 짝이다.
NO_RAW_BUS_ENV = "GELLO_NO_RAW_BUS"

#: 한 틱의 구성. 인덱스 0 은 시각(time.time), 나머지는 7개씩 묶인다.
#: 이름과 순서가 곧 저장 파일의 열 이름이 된다 -- 여기가 정본이다.
RAW_FIELDS = (
    "q",        # 측정 관절각 (rad)
    "q_d",      # 로봇이 받은 명령 관절각 (rad) -- q 와의 차이가 추종 지연
    "dq",       # 측정 관절속도 (rad/s) -- 진동의 주 신호
    "tau_J",    # 측정 관절토크 (N*m) -- 진동이 힘으로 보이는 곳
    "dtau_J",   # 토크 미분 -- 고주파 성분
    # 이것만 로봇이 아니라 **노드 내부** 값이다. 필터의 입력과 출력을 함께
    # 봐야 "계단이 얼마나 들어와서 얼마나 남았나" 를 잴 수 있다. 출력(q_d)만
    # 있으면 설정점 계단을 역산해야 한다 -- 2026-09-10 에 실제로 그랬다.
    "q_des",    # 워커가 보낸 설정점 (rad) = 기준 필터의 입력
    "q_cmd",    # **우리가 로봇에 실제로 쓴 명령** (rad) = 기준 필터의 출력.
                # q_d(로봇이 보고하는 desired)와 다르다 -- 2026-09-10 에
                # q_d 의 속도가 우리 v_max(1.5)를 넘는 1.81 rad/s 로 나와,
                # 그것이 우리 명령이 아님이 드러났다. 명령 스트림의 불연속을
                # 진단하려면 우리가 쓴 값 자체가 있어야 한다.
)

#: float64 로 저장할 필드. 나머지는 float32 다.
#:
#: 위치를 float32 로 낮추면 **이차미분이 망가진다**. 간격이 6e-8 rad 라
#: 이차미분에서 6e-8/1e-6 = 0.06 rad/s^2 씩 튀고, 실제 관측에서는 그 잡음이
#: 620 rad/s^2 짜리 가짜 봉우리로 보였다 (a_max 는 6 이다). 이 로거의 목적이
#: 바로 그 이차미분이라, 여기서 아끼면 안 된다.
FLOAT64_FIELDS = frozenset({"q", "q_d", "q_des", "q_cmd"})

DOF = 7

#: 시각 1 + 필드마다 7
RAW_LEN = 1 + len(RAW_FIELDS) * DOF


def field_slice(name: str) -> slice:
    """``name`` 필드가 한 틱 배열에서 차지하는 구간."""
    i = RAW_FIELDS.index(name)
    start = 1 + i * DOF
    return slice(start, start + DOF)
